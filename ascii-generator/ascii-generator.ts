const GLYPH: Record<AsciiStyle, { on: string; off: string }> = {
  block: { on: "██", off: "  " },
  slim: { on: "##", off: "  " },
  dots: { on: "██", off: "░░" },
  box: { on: "[]", off: "  " }
};

export function normalizeAsciiText(input: string): string {
  return input.replace(/\r/g, "").split("\n")[0].trim().slice(0, 40).toUpperCase();
}

export function generateAsciiText(input: string, style: AsciiStyle = "block"): string {
  const text = normalizeAsciiText(input);
  if (!text) return "";
  const glyph = GLYPH[style];
  const rows = Array.from({ length: 7 }, () => "");
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    const pattern = FONT[character] ?? FONT["?"];
    for (let row = 0; row < 7; row += 1) {
      rows[row] += pattern[row].replaceAll("1", glyph.on).replaceAll("0", glyph.off);
      if (index < text.length - 1) rows[row] += " ";
    }
  }
  return rows.join("\n");
}

export function frameAsciiArt(art: string, title = "ASCII ART"): string {
  const lines = art.split("\n");
  const width = Math.max(title.length, ...lines.map(line => line.length));
  const border = "+" + "-".repeat(width + 2) + "+";
  return [border, "| " + title.padEnd(width) + " |", border, ...lines.map(line => "| " + line.padEnd(width) + " |"), border].join("\n");
}
